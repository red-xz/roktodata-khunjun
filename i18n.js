export function t(lang, key) {
  if (STRINGS[lang] && STRINGS[lang][key] != null) return STRINGS[lang][key];
  if (STRINGS.en[key] != null) return STRINGS.en[key];
  return key;
}

export function langDir(code) {
  const l = LANGUAGES.find(x => x.code === code);
  return l ? l.dir : 'ltr';
}

